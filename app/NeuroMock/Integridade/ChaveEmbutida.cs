using System;
using System.Security.Cryptography;

namespace NeuroMock.Integridade;

/// <summary>
/// Segunda cópia da chave pública do fornecedor (v2), independente da que está no Core
/// (<c>ChaveFornecedor</c>): outra forma (o ponto X||Y da curva, mascarado) e outro assembly.
/// Trocar a chave pela de um atacante, para assinar licença e manifesto próprios, exige achar e
/// trocar as duas, porque cada guarda de integridade usa uma delas. A máscara não protege nada
/// criptograficamente: só tira esta cópia de uma busca pelo base64 ou pelo cabeçalho DER da chave.
/// </summary>
internal static class ChaveEmbutida
{
    private static ReadOnlySpan<byte> Mascarada =>
    [
        0xA0, 0xC2, 0xBD, 0xC7, 0xF8, 0xBA, 0x91, 0x83, 0x00, 0xEE, 0x8C, 0x9A, 0xE8, 0x8D, 0x7E, 0x47,
        0xEB, 0xA3, 0x28, 0x9A, 0xCB, 0x84, 0x56, 0x76, 0xC5, 0x91, 0xD9, 0xCB, 0xD6, 0x48, 0x0C, 0x68,
        0xF9, 0x82, 0x5F, 0x5C, 0xC4, 0x3E, 0x33, 0x9E, 0x41, 0x22, 0x7A, 0xA2, 0x10, 0x7F, 0xDB, 0xC5,
        0x3E, 0xEF, 0xF4, 0x8C, 0x4A, 0x2E, 0xB3, 0x00, 0xFE, 0x42, 0x0B, 0xD3, 0x33, 0xBB, 0xF8, 0x62,
    ];

    private static ReadOnlySpan<byte> Mascara =>
    [
        0x62, 0x52, 0x7C, 0xB3, 0x40, 0xCA, 0x00, 0x05, 0xBC, 0x71, 0xEC, 0xDF, 0x33, 0xCC, 0xB1, 0x4D,
        0x87, 0x25, 0x1A, 0x2B, 0xAD, 0xE6, 0x1B, 0x59, 0x5C, 0xA8, 0x14, 0x66, 0xB1, 0x9D, 0xF3, 0x36,
        0x31, 0x00, 0x9D, 0xDE, 0x89, 0x06, 0xBF, 0x43, 0xB0, 0xBA, 0xED, 0x2F, 0x48, 0x78, 0x93, 0xA7,
        0x27, 0x13, 0xD1, 0x56, 0x0C, 0x8C, 0xE8, 0x70, 0xA3, 0xDC, 0x6D, 0x6C, 0xF8, 0x8F, 0xBE, 0xE0,
    ];

    public static ECDsa Carregar()
    {
        var ponto = new byte[Mascarada.Length];
        for (var i = 0; i < ponto.Length; i++)
            ponto[i] = (byte)(Mascarada[i] ^ Mascara[i]);

        return ECDsa.Create(new ECParameters
        {
            Curve = ECCurve.NamedCurves.nistP256,
            Q = new ECPoint { X = ponto[..32], Y = ponto[32..] },
        });
    }
}
